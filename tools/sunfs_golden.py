#!/usr/bin/env python3
"""Independent Python LE/CRC golden page generator; no Rust serializer calls."""
import struct
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def crc64(data):
    c=0
    for b in data:
        c^=b<<56
        for _ in range(8): c=((c<<1)^ (0x42f0e1eba9ea3693 if c>>63 else 0))&((1<<64)-1)
    return c

def page(kind,address,epoch,birth,payload):
    b=bytearray(4096)
    struct.pack_into('<8sHHHH16sQQQI',b,0,b'SUNFSM02',kind,2,96,0,bytes(range(1,17)),address,epoch,birth,len(payload))
    b[96:96+len(payload)]=payload
    struct.pack_into('<Q',b,64,crc64(b))
    return bytes(b)

def generate():
    out=ROOT/'sunlight-sunfs/tests/fixtures'
    out.mkdir(parents=True,exist_ok=True)
    # Explicit externally generated bytes; exact integer positions independently laid out.
    sb=struct.pack('<4H3Q2I3Q3Q2Q2I2QI4x',0,2,0,2,0,0,3,4096,256,4096,256,15,2,3,4,128,32,82,6724,1069,526,0)
    assert len(sb)==136
    inode=struct.pack('<QQBBHIIIQQQQ',1,1,2,0,0o755,0,0,2,0,1,1,1)
    inode+=bytes(24)+struct.pack('<QQQ',257,1,0x0123456789abcdef)+bytes(88)
    assert len(inode)==200
    directory=struct.pack('<QQII',1,1,0,1)+struct.pack('<II',40,0)
    directory+=struct.pack('<QQHBBH10x',2,1,1,1,0,40)+b'x'+bytes(7)
    root=struct.pack('<HHIQII',3,0,0,0,32,0)
    entries={'superblock.bin':page(1,0,0,0,sb),'inode.bin':page(5,256,1,1,inode),
             'directory.bin':page(6,258,1,1,directory),'empty-orphan-root.bin':page(3,259,1,1,root)}
    for name,data in entries.items(): (out/name).write_bytes(data)
    return entries
if __name__=='__main__':
    assert crc64(b'123456789')==0x6c40df5f0b497347
    import hashlib
    for name,data in generate().items(): print(name,hashlib.sha256(data).hexdigest())
